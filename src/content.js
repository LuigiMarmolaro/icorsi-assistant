  // Riconosce PDF/PPTX/DOCX dal content-type o, come ripiego (es.
  // application/octet-stream), dall'estensione nell'URL finale
  function guessBinaryKind(ctype, url) {
    if (ctype.includes('application/pdf') || /\.pdf(\?|#|$)/i.test(url)) return 'pdf';
    if (ctype.includes('presentationml') || /\.pptx(\?|#|$)/i.test(url)) return 'pptx';
    if (ctype.includes('wordprocessingml') || /\.docx(\?|#|$)/i.test(url)) return 'docx';
    return null;
  }

  async function fetchResource(item, condHeaders = {}) {
    const resp = await fetch(item.url, {
      credentials: 'include',
      redirect: 'follow',
      headers: condHeaders,
    });
    // 304 = il server conferma che il contenuto non è cambiato
    if (resp.status === 304) return { type: 'unchanged' };
    if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
    const ctype = (resp.headers.get('content-type') || '').toLowerCase();
    const validators = {
      etag: resp.headers.get('etag') || null,
      lastModified: resp.headers.get('last-modified') || null,
    };

    const binaryKind = guessBinaryKind(ctype, resp.url);
    if (binaryKind) {
      const buf = await resp.arrayBuffer();
      if (buf.byteLength > MAX_FILE_BYTES) throw new Error('File troppo grande, saltato');
      return { type: binaryKind, buf, finalUrl: resp.url, ...validators };
    }

    if (ctype.includes('text/html')) {
      const html = await resp.text();
      if (looksLikeLogin(resp.url, html)) {
        throw new Error('Sessione scaduta: effettua di nuovo il login su iCorsi');
      }
      const doc = new DOMParser().parseFromString(html, 'text/html');

      // mod/resource a volte restituisce una pagina HTML che incapsula il
      // file vero: cerchiamo il link/embed interno (workaround standard Moodle)
      if (item.kind === 'resource') {
        const inner =
          doc.querySelector('.resourceworkaround a[href]')?.href ||
          doc.querySelector('object[data]')?.getAttribute('data') ||
          doc.querySelector('iframe#resourceobject')?.src ||
          doc.querySelector('.resourcecontent a[href]')?.href;
        if (inner) {
          const innerUrl = new URL(inner, resp.url).href;
          if (innerUrl.startsWith(location.origin)) {
            const r2 = await fetch(innerUrl, { credentials: 'include' });
            const kind2 = r2.ok
              ? guessBinaryKind((r2.headers.get('content-type') || '').toLowerCase(), r2.url)
              : null;
            if (kind2) {
              const buf = await r2.arrayBuffer();
              if (buf.byteLength > MAX_FILE_BYTES) throw new Error('File troppo grande, saltato');
              return { type: kind2, buf, finalUrl: r2.url, ...validators };
            }
          }
        }
        throw new Error('Formato non supportato (gestiti: PDF, PPTX, DOCX, pagine)');
      }

      // mod/page: estraiamo il testo del contenuto principale
      const main =
        doc.querySelector('#region-main') ||
        doc.querySelector('[role="main"]') ||
        doc.body;
      main.querySelectorAll('script, style, nav, footer, .activity-navigation')
        .forEach((el) => el.remove());
      const text = main.innerText.replace(/\n{3,}/g, '\n\n').trim();
      return { type: 'html', text, finalUrl: resp.url, ...validators };
    }

    throw new Error(`Tipo di contenuto non supportato: ${ctype.split(';')[0] || 'sconosciuto'}`);
  }

  async function extractPdfText(buf) {
    const pdfjs = await loadPdfJs();
    const pdf = await pdfjs.getDocument({ data: buf }).promise;
    const pages = [];
    let totalChars = 0;
    for (let p = 1; p <= pdf.numPages; p++) {
      const page = await pdf.getPage(p);
      const content = await page.getTextContent();
      const text = content.items
        .map((it) => it.str)
        .join(' ')
        .replace(/\s+/g, ' ')
        .trim();
      totalChars += text.length;
      pages.push({ page: p, text });
    }
    const probablyScanned = pdf.numPages > 0 && totalChars / pdf.numPages < 40;
    await pdf.destroy();
    return { pages, numPages: pdf.numPages, probablyScanned };
  }

