  function sendBg(msg) {
    return new Promise((resolve) =>
      chrome.runtime.sendMessage(msg, (resp) => {
        if (chrome.runtime.lastError) {
          resolve({ ok: false, error: chrome.runtime.lastError.message });
        } else {
          resolve(resp);
        }
      })
    );
  }

  async function indexInBackground(doc, chunks) {
    const resp = await sendBg({ type: 'INDEX_DOC', doc, chunks });
    if (!resp?.ok) {
      throw new Error(`indicizzazione fallita: ${resp?.error || 'nessuna risposta dal background'}`);
    }
  }

  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

  async function scanPage(onProgress) {
    const report = { indexed: 0, unchanged: 0, skipped: [], warnings: [] };
    const { excludePatterns, deepScan } = await chrome.storage.local.get([
      'excludePatterns', 'deepScan',
    ]);
    const excludes = (excludePatterns ?? DEFAULT_EXCLUDES)
      .split('\n')
      .map((s) => s.trim().toLowerCase())
      .filter(Boolean);

    // 0. pulizia retroattiva: i documenti già indicizzati che ora ricadono
    //    nella lista di esclusione vengono rimossi dall'indice
    try {
      const purge = await sendBg({ type: 'REMOVE_MATCHING', patterns: excludes });
      if (purge?.removed?.length > 0) {
        report.warnings.push(t('removedExcluded', purge.removed.length, purge.removed.join('", "')));
      }
    } catch (_) { /* non bloccante */ }

    // 1. testo visibile della pagina corrente
    onProgress(t('statusScanPage'));
    try {
      const pageData = extractCurrentPageChunks();
      if (pageData.chunks.length > 0) {
        const pageHash = await sha256(pageData.chunks.map((c) => c.text).join('\n'));
        const chk = await sendBg({ type: 'CHECK_DOC', docId: pageData.doc.id, contentHash: pageHash });
        if (chk?.unchanged) {
          report.unchanged++;
        } else {
          pageData.doc.contentHash = pageHash;
          await indexInBackground(pageData.doc, pageData.chunks);
          report.indexed++;
        }
      } else {
        report.warnings.push(t('warnNoPageText'));
      }
    } catch (e) {
      report.skipped.push(`${t('currentPage')} — ${e.message}`);
    }

    // 2. link della pagina corrente + esplorazione delle sottopagine
    //    (sezioni del corso e cartelle): i materiali trovati lì dentro
    //    si aggiungono alla coda, il testo delle sezioni viene indicizzato
    const found = extractLinks(document, location.href, excludes);
    const materials = found.materials;
    // L'esplorazione delle sottopagine è opt-in: di default si analizzano
    // solo i documenti visibili sulla dashboard del corso
    const containers = deepScan === true ? found.containers.slice(0, MAX_SUBPAGES) : [];
    if (deepScan === true && found.containers.length > MAX_SUBPAGES) {
      report.warnings.push(t('warnSubpages', found.containers.length, MAX_SUBPAGES));
    }

    for (const cont of containers) {
      onProgress(t(cont.kind === 'folder' ? 'statusExploreFolder' : 'statusExploreSection', cont.title));
      try {
        const resp = await fetch(cont.url, { credentials: 'include', redirect: 'follow' });
        if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
        const html = await resp.text();
        if (looksLikeLogin(resp.url, html)) {
          throw new Error('Sessione scaduta: effettua di nuovo il login su iCorsi');
        }
        const sub = new DOMParser().parseFromString(html, 'text/html');

        // materiali linkati nella sottopagina
        const subLinks = extractLinks(sub, resp.url, excludes);
        for (const m of subLinks.materials) {
          if (!materials.some((x) => x.url === m.url)) materials.push(m);
        }

        // testo delle sezioni (le cartelle sono solo elenchi di file)
        if (cont.kind === 'section') {
          const main = sub.querySelector('#region-main, [role="main"]') || sub.body;
          main.querySelectorAll('script, style, nav, footer').forEach((n) => n.remove());
          const text = (main.innerText || main.textContent || '')
            .replace(/\n{3,}/g, '\n\n')
            .trim();
          if (text.length > 80) {
            const docId = hashId(cont.url);
            const contentHash = await sha256(text);
            const chk = await sendBg({ type: 'CHECK_DOC', docId, contentHash });
            if (chk?.unchanged) {
              report.unchanged++;
            } else {
              const chunks = chunkString(text, {
                docId, title: cont.title, url: cont.url, page: null,
              });
              if (chunks.length > 0) {
                await indexInBackground(
                  { id: docId, title: cont.title, url: cont.url, kind: 'coursepage', contentHash },
                  chunks
                );
                report.indexed++;
              }
            }
          }
        }
      } catch (e) {
        report.skipped.push(`${cont.title} — ${e.message}`);
      }
      await sleep(FETCH_DELAY_MS);
    }

    let links = materials;
    if (links.length > MAX_DOCS_PER_SCAN) {
      report.warnings.push(t('warnTooMany', links.length, MAX_DOCS_PER_SCAN));
      links = links.slice(0, MAX_DOCS_PER_SCAN);
    }
    onProgress(t('statusFound', links.length));

    let done = 0;
    const queue = [...links];
    async function worker() {
      while (queue.length > 0) {
        const item = queue.shift();
        done++;
        onProgress(`(${done}/${links.length}) ${item.title}`);
        try {
          const docId = hashId(item.url);

          // scansione incrementale, livello 1: validatori HTTP del server
          const prev = await sendBg({ type: 'GET_DOC', docId });
          const condHeaders = {};
          if (prev?.doc?.etag) condHeaders['If-None-Match'] = prev.doc.etag;
          if (prev?.doc?.lastModified) condHeaders['If-Modified-Since'] = prev.doc.lastModified;

          const res = await fetchResource(item, condHeaders);
          if (res.type === 'unchanged') {
            report.unchanged++;
          } else {
            // livello 2: hash del contenuto (se il server non supporta i 304,
            // si evita comunque il costo di parsing + embeddings)
            const contentHash = await sha256(res.buf || res.text);
            const chk = await sendBg({ type: 'CHECK_DOC', docId, contentHash });
            if (chk?.unchanged) {
              report.unchanged++;
            } else {
              let chunks = [];
              const doc = {
                id: docId,
                title: item.title,
                url: item.url,
                kind: res.type,
                contentHash,
                etag: res.etag || null,
                lastModified: res.lastModified || null,
              };
              if (res.type === 'pdf') {
                const { pages, numPages, probablyScanned } = await extractPdfText(res.buf);
                if (probablyScanned) {
                  report.warnings.push(t('warnScanned', item.title));
                }
                doc.pages = numPages;
                chunks = chunkPdf(pages, { docId, title: item.title, url: item.url });
              } else if (res.type === 'pptx') {
                const pages = await extractPptxText(res.buf);
                doc.pages = pages.length;
                chunks = chunkPdf(pages, { docId, title: item.title, url: item.url });
              } else if (res.type === 'docx') {
                const text = await extractDocxText(res.buf);
                chunks = chunkString(text, { docId, title: item.title, url: item.url, page: null });
              } else if (res.type === 'html') {
                chunks = chunkString(res.text, { docId, title: item.title, url: item.url, page: null });
              }
              if (chunks.length > 0) {
                await indexInBackground(doc, chunks);
                report.indexed++;
              } else {
                report.skipped.push(`${item.title} (${t('warnNoPageText')})`);
              }
            }
          }
        } catch (e) {
          report.skipped.push(`${item.title} — ${e.message}`);
        }
        await sleep(FETCH_DELAY_MS);
      }
    }
    await Promise.all(Array.from({ length: FETCH_CONCURRENCY }, worker));
    return report;
  }

  // -------------------------------------------------------------------------
  // Mini-renderer Markdown (DOM-safe: niente innerHTML, quindi niente XSS
  // anche se il modello ricopiasse testo ostile dalla pagina).
  // Supporta: titoli, liste, blocchi di codice, **grassetto**, *corsivo*,
  // `codice`, [testo](url) e citazioni [n] linkate alle fonti.
  // -------------------------------------------------------------------------

  function mkLink(href, text) {
    const a = document.createElement('a');
    a.href = href;
    a.target = '_blank';
    a.rel = 'noopener';
    a.textContent = text;
    return a;
  }

  function appendInline(node, text, sources) {
    const re =
      /(`[^`\n]+`)|(\*\*[^*\n]+\*\*)|(\*[^*\n]+\*)|\[([^\]\n]+)\]\((https?:\/\/[^\s)]+)\)|(\[(\d{1,2})\])/g;
    let last = 0;
    let m;
    while ((m = re.exec(text))) {
      if (m.index > last) node.appendChild(document.createTextNode(text.slice(last, m.index)));
      if (m[1]) {
        const c = document.createElement('code');
        c.textContent = m[1].slice(1, -1);
        node.appendChild(c);
      } else if (m[2]) {
        const b = document.createElement('strong');
        b.textContent = m[2].slice(2, -2);
        node.appendChild(b);
      } else if (m[3]) {
        const i2 = document.createElement('em');
        i2.textContent = m[3].slice(1, -1);
        node.appendChild(i2);
      } else if (m[4] && m[5]) {
        node.appendChild(mkLink(m[5], m[4]));
      } else if (m[6]) {
        const n = parseInt(m[7], 10);
        const src = sources && sources.find((s) => s.n === n);
        if (src) {
          // ancora #page=N: il viewer PDF di Chrome apre alla pagina citata
          const a = mkLink(src.page ? `${src.url}#page=${src.page}` : src.url, `[${n}]`);
          a.className = 'ica-cite';
          a.title = src.title + (src.page ? ` — ${t('pageAbbr')} ${src.page}` : '');
          node.appendChild(a);
        } else {
          node.appendChild(document.createTextNode(m[6]));
        }
      }
      last = re.lastIndex;
    }
    if (last < text.length) node.appendChild(document.createTextNode(text.slice(last)));
  }

  function mdToFragment(md, sources) {
    const frag = document.createDocumentFragment();
    const lines = md.split('\n');
    let i = 0;
    let listEl = null;
    let listType = null;
    const flushList = () => {
      listEl = null;
      listType = null;
    };
    const isSpecial = (l) =>
      /^(#{1,4}\s|```|\s*[-*•]\s+|\s*\d+[.)]\s+)/.test(l);

    while (i < lines.length) {
      const line = lines[i];

      if (/^```/.test(line)) {
        const buf = [];
        i++;
        while (i < lines.length && !/^```/.test(lines[i])) buf.push(lines[i++]);
        i++; // fence di chiusura
        const pre = document.createElement('pre');
        const code = document.createElement('code');
        code.textContent = buf.join('\n');
        pre.appendChild(code);
        frag.appendChild(pre);
        flushList();
        continue;
      }

      const h = line.match(/^(#{1,4})\s+(.*)/);
      if (h) {
        const hEl = document.createElement('h' + Math.min(h[1].length + 2, 6));
        appendInline(hEl, h[2], sources);
        frag.appendChild(hEl);
        flushList();
        i++;
        continue;
      }

      const ul = line.match(/^\s*[-*•]\s+(.*)/);
      const ol = line.match(/^\s*\d+[.)]\s+(.*)/);
      if (ul || ol) {
        const type = ul ? 'ul' : 'ol';
        if (!listEl || listType !== type) {
          listEl = document.createElement(type);
          frag.appendChild(listEl);
          listType = type;
        }
        const li = document.createElement('li');
        appendInline(li, ul ? ul[1] : ol[1], sources);
        listEl.appendChild(li);
        i++;
        continue;
      }

      if (!line.trim()) {
        flushList();
        i++;
        continue;
      }

      // paragrafo: accorpa le righe consecutive non speciali
      const buf = [line];
      i++;
      while (i < lines.length && lines[i].trim() && !isSpecial(lines[i])) buf.push(lines[i++]);
      const p = document.createElement('p');
      appendInline(p, buf.join(' '), sources);
      frag.appendChild(p);
      flushList();
    }
    return frag;
  }

  function renderMarkdown(container, text, sources) {
    container.textContent = '';
    container.appendChild(mdToFragment(text, sources));
  }

