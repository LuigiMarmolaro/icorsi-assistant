  // PPTX / DOCX — sono archivi ZIP di XML: niente librerie esterne, basta un
  // mini-lettore ZIP con DecompressionStream (nativo nel browser)
  // -------------------------------------------------------------------------

  async function unzip(buf, nameFilter) {
    const view = new DataView(buf);
    const bytes = new Uint8Array(buf);

    // End Of Central Directory: si cerca la firma dal fondo del file
    let eocd = -1;
    const stop = Math.max(0, buf.byteLength - 22 - 65536);
    for (let i = buf.byteLength - 22; i >= stop; i--) {
      if (view.getUint32(i, true) === 0x06054b50) {
        eocd = i;
        break;
      }
    }
    if (eocd < 0) throw new Error('archivio ZIP non valido');

    const count = view.getUint16(eocd + 10, true);
    let off = view.getUint32(eocd + 16, true);
    const files = new Map();
    for (let n = 0; n < count; n++) {
      if (view.getUint32(off, true) !== 0x02014b50) break;
      const method = view.getUint16(off + 10, true);
      const compSize = view.getUint32(off + 20, true);
      const nameLen = view.getUint16(off + 28, true);
      const extraLen = view.getUint16(off + 30, true);
      const commentLen = view.getUint16(off + 32, true);
      const localOff = view.getUint32(off + 42, true);
      const name = new TextDecoder().decode(bytes.subarray(off + 46, off + 46 + nameLen));
      off += 46 + nameLen + extraLen + commentLen;

      if (!nameFilter(name)) continue; // si decomprime solo il necessario
      // l'header locale può avere lunghezze extra diverse dal central directory
      const lnl = view.getUint16(localOff + 26, true);
      const lel = view.getUint16(localOff + 28, true);
      const dataStart = localOff + 30 + lnl + lel;
      const comp = bytes.subarray(dataStart, dataStart + compSize);
      if (method === 0) {
        files.set(name, comp); // non compresso
      } else if (method === 8) {
        const stream = new Blob([comp]).stream().pipeThrough(
          new DecompressionStream('deflate-raw')
        );
        files.set(name, new Uint8Array(await new Response(stream).arrayBuffer()));
      }
    }
    return files;
  }

  function xmlTexts(xmlBytes, localName) {
    const xml = new TextDecoder().decode(xmlBytes);
    const doc = new DOMParser().parseFromString(xml, 'application/xml');
    return [...doc.getElementsByTagNameNS('*', localName)];
  }

  // DOCX: il testo vive in word/document.xml, paragrafi <w:p> con run <w:t>
  async function extractDocxText(buf) {
    const files = await unzip(buf, (n) => n === 'word/document.xml');
    const docXml = files.get('word/document.xml');
    if (!docXml) throw new Error('DOCX senza word/document.xml');
    const paras = xmlTexts(docXml, 'p')
      .map((p) =>
        [...p.getElementsByTagNameNS('*', 't')].map((t) => t.textContent).join('')
      )
      .filter((s) => s.trim());
    return paras.join('\n');
  }

  // PPTX: una slide = ppt/slides/slideN.xml; il testo è negli elementi <a:t>.
  // Ritorna pagine numerate come i PDF, così le citazioni dicono la slide.
  async function extractPptxText(buf) {
    const isSlide = (n) => /^ppt\/slides\/slide\d+\.xml$/.test(n);
    const files = await unzip(buf, isSlide);
    const slideNum = (n) => parseInt(n.match(/slide(\d+)\.xml$/)[1], 10);
    const names = [...files.keys()].sort((a, b) => slideNum(a) - slideNum(b));
    return names.map((name) => ({
      page: slideNum(name),
      text: xmlTexts(files.get(name), 't')
        .map((t) => t.textContent)
        .join(' ')
        .replace(/\s+/g, ' ')
        .trim(),
    }));
  }

