  function chunkString(text, meta) {
    const chunks = [];
    let start = 0;
    while (start < text.length) {
      let end = Math.min(start + CHUNK_SIZE, text.length);
      // prova a tagliare su un confine di frase
      if (end < text.length) {
        const cut = text.lastIndexOf('. ', end);
        if (cut > start + CHUNK_SIZE * 0.5) end = cut + 1;
      }
      const piece = text.slice(start, end).trim();
      if (piece.length > 50) chunks.push({ ...meta, text: piece });
      if (end >= text.length) break;
      start = end - CHUNK_OVERLAP;
    }
    return chunks;
  }

  function chunkPdf(pages, meta) {
    const chunks = [];
    for (const { page, text } of pages) {
      if (!text) continue;
      chunks.push(...chunkString(text, { ...meta, page }));
    }
    return chunks;
  }

  function hashId(s) {
    let h = 5381;
    for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0;
    return 'doc_' + h.toString(16);
  }

