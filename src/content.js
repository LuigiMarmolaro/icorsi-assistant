  function extractLinks(rootEl, baseUrl, excludes = []) {
    const materials = [];
    const containers = [];
    const seen = new Set();
    for (const a of rootEl.querySelectorAll('a[href]')) {
      const raw = a.getAttribute('href');
      if (!raw || raw.startsWith('#') || raw.startsWith('javascript:')) continue;
      let abs;
      try {
        abs = new URL(raw, baseUrl).href;
      } catch (_) {
        continue;
      }
      if (!abs.startsWith(location.origin)) continue; // solo same-origin
      const url = abs.split('#')[0];
      if (seen.has(url)) continue;
      const label =
        a.querySelector('.instancename')?.childNodes[0]?.textContent?.trim() ||
        a.textContent.trim().replace(/\s+/g, ' ').slice(0, 120) ||
        decodeURIComponent(url.split('/').pop().split('?')[0]);
      // lista di esclusione configurabile (es. file Teams/SharePoint)
      const lcUrl = url.toLowerCase();
      const lcLabel = label.toLowerCase();
      if (excludes.some((p) => p && (lcUrl.includes(p) || lcLabel.includes(p)))) continue;
      const fm = FILE_PATTERNS.find((p) => p.re.test(url));
      if (fm) {
        seen.add(url);
        materials.push({ url, kind: fm.kind, title: label });
        continue;
      }
      const cm = CONTAINER_PATTERNS.find((p) => p.re.test(url));
      if (cm && url !== location.href.split('#')[0]) {
        seen.add(url);
        containers.push({ url, kind: cm.kind, title: label });
      }
    }
    return { materials, containers };
  }

